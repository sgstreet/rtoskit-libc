#include <rtos/rtos-port.h>

#include "rtos-none.h"

/* Every lock is a no-op, so they can all share one object */
int __rtos_lock_create(struct __rtos_lock **lock)
{
	static struct __rtos_lock shared;

	*lock = &shared;
	return 0;
}
