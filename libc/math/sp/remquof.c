#include <math.h>
#include <stdint.h>

#include "internal/math.h"

/* C23 7.12.10.3: remainderf, with the sign and low bits of the quotient in *quo */
float remquof(float x, float y, int *quo)
{
	return __libc_remainderf(x, y, true, quo);
}
